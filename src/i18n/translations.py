def t(key: str, lang: str = "vi", **kwargs) -> str:
    """
    Hàm trợ lý lấy chuỗi văn bản dịch thuật theo ngôn ngữ chỉ định.
    """
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS["vi"])
    raw_text = lang_dict.get(key, TRANSLATIONS["vi"].get(key, key))
    if kwargs:
        try:
            return raw_text.format(**kwargs)
        except Exception:
            return raw_text
    return raw_text
